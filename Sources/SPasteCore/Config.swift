import Foundation
import SCommon

/// The global key that opens and closes the panel. Unlike keymap keys,
/// `shift-` stays on a letter (`shift-cmd-c`); an upper-case letter means
/// the same.
public struct Hotkey: Sendable, Equatable, CustomStringConvertible {
    /// A lower-case character, or a name from `Key.names`.
    public let key: String
    public let modifiers: Key.Modifiers

    public static let `default` = Hotkey(key: "c", modifiers: [.shift, .command])

    public init(
        key: String,
        modifiers: Key.Modifiers
    ) {
        self.key = key
        self.modifiers = modifiers
    }

    private static let modifierNames: [(String, Key.Modifiers)] = [
        ("cmd", .command),
        ("ctrl", .control),
        ("alt", .option),
        ("shift", .shift),
    ]

    /// Nil when the text is not a key, or a character key has no cmd, ctrl
    /// or alt and would swallow typing everywhere.
    public static func parse(_ text: String) -> Hotkey? {
        var tokens = text.split(separator: "-", omittingEmptySubsequences: false).map(String.init)
        guard var base = tokens.popLast() else {
            return nil
        }
        if base.isEmpty, tokens.last == "" {
            // `cmd--` binds the minus key
            tokens.removeLast()
            base = "-"
        }
        var modifiers: Key.Modifiers = []
        for token in tokens {
            guard let modifier = modifierNames.first(where: { $0.0 == token.lowercased() })?.1 else {
                return nil
            }
            modifiers.insert(modifier)
        }
        if base.count == 1 {
            if base.first!.isUppercase {
                modifiers.insert(.shift)
            }
            base = base.lowercased()
            guard !modifiers.isDisjoint(with: [.command, .control, .option]) else {
                return nil
            }
        } else {
            base = base.lowercased()
            guard Key.names.contains(base), base.hasPrefix("f") || !modifiers.isDisjoint(with: [.command, .control, .option]) else {
                return nil
            }
        }
        return Hotkey(key: base, modifiers: modifiers)
    }

    public var description: String {
        (Self.modifierNames.filter { modifiers.contains($0.1) }.map(\.0) + [key]).joined(separator: "-")
    }
}

/// Settings from `~/.config/spaste/config`. Unknown keys and bad values are
/// reported as issues and leave the default in place, so a typo never stops
/// the app from starting.
public struct Config: KeyValueSettings, Equatable {
    public var hotkey = Hotkey.default
    public var maxItems = 500
    public var maxImageMB = 20
    public var pollMilliseconds = 500
    public var pasteOnEnter = false
    /// Bundle ids whose copies are never stored, from repeated lines.
    public var ignoreApps: [String] = []
    /// Pasteboard types that keep a copy out of the history, on top of the
    /// concealed, transient and auto-generated markers.
    public var ignoreTypes: [String] = []

    public init() {}

    /// Always skipped: what password managers and generated content set.
    public static let skippedTypes = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public enum SetError: Error, Equatable, CustomStringConvertible {
        case unknownKey(String)
        case badValue(key: String, value: String, expected: String)

        public var description: String {
            switch self {
            case .unknownKey(let key):
                return "unknown option '\(key)'"
            case .badValue(let key, let value, let expected):
                return "\(key): '\(value)' is not \(expected)"
            }
        }
    }

    public mutating func set(
        _ key: String,
        _ value: String
    ) throws(SetError) {
        switch key {
        case "hotkey":
            guard let parsed = Hotkey.parse(value) else {
                throw .badValue(key: key, value: value, expected: "a key with cmd, ctrl or alt, such as shift-cmd-c")
            }
            hotkey = parsed
        case "max_items":
            maxItems = try Self.int(key, value, range: 10...100_000)
        case "max_image_mb":
            maxImageMB = try Self.int(key, value, range: 1...500)
        case "poll_ms":
            pollMilliseconds = try Self.int(key, value, range: 100...5000)
        case "paste_on_enter":
            pasteOnEnter = try Self.bool(key, value)
        case "ignore_app":
            ignoreApps.append(try Self.word(key, value, "a bundle id"))
        case "ignore_type":
            ignoreTypes.append(try Self.word(key, value, "a pasteboard type"))
        default:
            throw .unknownKey(key)
        }
    }

    static func int(
        _ key: String,
        _ value: String,
        range: ClosedRange<Int>
    ) throws(SetError) -> Int {
        guard let n = Int(value), range.contains(n) else {
            throw .badValue(key: key, value: value, expected: "a number from \(range.lowerBound) to \(range.upperBound)")
        }
        return n
    }

    static func bool(
        _ key: String,
        _ value: String
    ) throws(SetError) -> Bool {
        switch value.lowercased() {
        case "yes", "true", "on":
            return true
        case "no", "false", "off":
            return false
        default:
            throw .badValue(key: key, value: value, expected: "yes or no")
        }
    }

    static func word(
        _ key: String,
        _ value: String,
        _ expected: String
    ) throws(SetError) -> String {
        guard !value.isEmpty, !value.contains(where: \.isWhitespace) else {
            throw .badValue(key: key, value: value, expected: expected)
        }
        return value
    }

    public static let defaultText = """
        # sPaste config. One setting per line: <key> <value>. Lines starting
        # with # are comments. Problems show in the panel's status line.

        # the global key that opens and closes the panel
        hotkey shift-cmd-c

        # unpinned items kept; the oldest go first and their files are deleted
        max_items 500

        # images larger than this are not stored
        max_image_mb 20

        # how often the clipboard is checked, in milliseconds
        poll_ms 500

        # yes: enter also pastes into the app you came from (needs Accessibility)
        paste_on_enter no

        # apps whose copies are never stored, one line each
        # ignore_app com.example.vault

        # pasteboard types that keep a copy out of the history, one line each;
        # concealed, transient and auto-generated items are always skipped
        # ignore_type com.agilebits.onepassword
        """
}
